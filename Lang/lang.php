// Fonction de traduction
function t($key, $params = []) {
    global $lang;

    $text = $lang[$key] ?? $key;

    // Remplace les paramètres dynamiques
    foreach ($params as $param => $value) {
        $text = str_replace($param, $value, $text);
    }

    return $text;
}
